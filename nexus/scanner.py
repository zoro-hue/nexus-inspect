"""Repository scanner: walks a directory tree under hard limits, runs rules, normalizes findings."""
import hashlib
import os
import time
from collections import Counter
from dataclasses import dataclass, field
from typing import Dict, List, Optional

from . import ast_rules as A
from . import graph as G
from . import rules as R

MAX_FILES = 5000
MAX_FILE_BYTES = 512 * 1024
DEFAULT_TIME_BUDGET = 60.0
SKIP_DIRS = {".git", "node_modules", "vendor", "__pycache__", "dist", "build", ".venv", "venv", "target", ".next"}
SEVERITY_WEIGHT = {"critical": 40, "high": 25, "medium": 12, "low": 4}
LANG_BY_EXT = {
    ".py": "Python", ".js": "JavaScript", ".mjs": "JavaScript", ".cjs": "JavaScript", ".jsx": "JavaScript",
    ".ts": "TypeScript", ".tsx": "TypeScript", ".go": "Go", ".java": "Java", ".rb": "Ruby", ".php": "PHP",
}
ENTRY_HINTS = {"main.py", "app.py", "server.py", "server.js", "index.js", "index.ts", "main.go", "app.js"}
MANIFESTS = {"package.json", "requirements.txt", "pyproject.toml", "go.mod", "pom.xml", "Gemfile", "composer.json"}


@dataclass
class ScanResult:
    findings: List[dict] = field(default_factory=list)
    files_scanned: int = 0
    files_skipped: Dict[str, int] = field(default_factory=dict)
    languages: Dict[str, int] = field(default_factory=dict)
    manifests: List[str] = field(default_factory=list)
    entry_points: List[str] = field(default_factory=list)
    partial: bool = False
    partial_reason: Optional[str] = None
    file_index: List[dict] = field(default_factory=list)
    parse_failures: List[str] = field(default_factory=list)
    deduplicated: int = 0
    edges: List[dict] = field(default_factory=list)


def _skip(result, reason):
    result.files_skipped[reason] = result.files_skipped.get(reason, 0) + 1


def collect_files(root: str, result: ScanResult):
    """Return {relative_path: text} for text files under root, enforcing limits."""
    texts = {}
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".git"))
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            if os.path.islink(full):
                _skip(result, "symlink")
                continue
            if len(texts) >= MAX_FILES:
                result.partial, result.partial_reason = True, f"file limit of {MAX_FILES} reached"
                return texts
            try:
                size = os.path.getsize(full)
            except OSError:
                _skip(result, "unreadable")
                continue
            if size > MAX_FILE_BYTES:
                _skip(result, "too_large")
                continue
            with open(full, "rb") as fh:
                raw = fh.read()
            if b"\x00" in raw[:4096]:
                _skip(result, "binary")
                continue
            if not R.is_text_file(rel) and os.path.basename(rel) not in MANIFESTS:
                _skip(result, "unsupported_type")
                continue
            text = raw.decode("utf-8", errors="replace")
            if _is_generated(text):
                _skip(result, "generated")
                continue
            if _is_minified(text):
                _skip(result, "minified")
                continue
            texts[rel] = text
    return texts


GENERATED_MARKERS = ("code generated", "@generated", "do not edit", "auto-generated", "autogenerated")
MINIFIED_LINE_CHARS = 2000


def _is_generated(text):
    """Generator headers appear at the top of a file; scanning only the first lines keeps this cheap."""
    head = text[:1024].lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def _is_minified(text):
    """A single very long line is a bundle or a minified file, where line numbers are meaningless."""
    return any(len(line) > MINIFIED_LINE_CHARS for line in text.splitlines())


def _fingerprint(rule_id, path, line):
    return "NX-" + hashlib.sha1(f"{rule_id}|{path}|{line}".encode()).hexdigest()[:12]


EXCERPT_CONTEXT = 2
EXCERPT_MAX_CHARS = 240


def _excerpt(lines, start, end):
    """Numbered, redacted context around a finding, never the raw secret value. Lines inside a private key block
    are replaced entirely, because key material cannot be recognised one line at a time."""
    first = max(1, start - EXCERPT_CONTEXT)
    last = min(len(lines), end + EXCERPT_CONTEXT)
    keyed = R.pem_body_lines(lines)
    return [{"line": n,
             "text": (R.PEM_REDACTED if n in keyed else R.redact_line(lines[n - 1])[:EXCERPT_MAX_CHARS]),
             "highlight": start <= n <= end}
            for n in range(first, last + 1)]


def _normalize(rule, path, hit, created_at, lines=()):
    lines_end = hit.end_line or hit.line
    return {
        "id": _fingerprint(rule.id, path, hit.line),
        "ruleId": rule.id,
        "title": rule.title,
        "category": rule.category,
        "severity": rule.severity,
        "confidence": rule.confidence,
        "status": "open",
        "evidenceClass": rule.evidence_class,
        "filePath": path,
        "startLine": hit.line,
        "endLine": lines_end,
        "evidence": hit.evidence,
        "explanation": hit.explanation or rule.title + ".",
        "impact": rule.impact,
        "remediation": rule.remediation,
        "verificationSteps": list(rule.verification),
        "relatedFindings": [],
        "detectionMethod": rule.method if rule.method != "pattern" else "pattern",
        "riskScore": 0,
        "createdAt": created_at,
        "excerpt": _excerpt(lines, hit.line, lines_end) if lines else [],
    }


def _deduplicate(findings):
    """Same file, same line and same category usually means one construct flagged twice. Keep the strongest
    finding and record the other rule IDs in its explanation so nothing is silently dropped."""
    groups, kept, dropped = {}, [], 0
    for f in findings:
        # File-level and import-graph findings describe the whole module, not a construct on a line, so they never merge.
        if f["detectionMethod"] != "pattern":
            kept.append(f)
            continue
        groups.setdefault((f["filePath"], f["startLine"], f["category"]), []).append(f)
    for members in groups.values():
        if len(members) == 1:
            kept.append(members[0])
            continue
        members.sort(key=lambda f: (-f["confidence"], f["ruleId"]))
        best = members[0]
        others = [m["ruleId"] for m in members[1:]]
        best["explanation"] = f"{best['explanation']} Also matched by {', '.join(others)} on the same line."
        dropped += len(others)
        kept.append(best)
    return kept, dropped


def _correlate_and_score(findings):
    by_file = {}
    for f in findings:
        by_file.setdefault(f["filePath"], []).append(f)
    for f in findings:
        peers = [p["id"] for p in by_file[f["filePath"]] if p["id"] != f["id"]]
        f["relatedFindings"] = peers
        base = SEVERITY_WEIGHT[f["severity"]] * f["confidence"]
        f["riskScore"] = round(min(100.0, base + 2 * len(peers)), 1)
    findings.sort(key=lambda f: (-f["riskScore"], f["filePath"], f["startLine"]))
    return findings


def scan(root: str, created_at: str, time_budget: float = DEFAULT_TIME_BUDGET, on_stage=None) -> ScanResult:
    emit = on_stage or (lambda stage, progress: None)
    result = ScanResult()
    started = time.monotonic()
    emit('file_indexing', 45)
    texts = collect_files(root, result)
    emit('architecture', 55)
    result.files_scanned = len(texts)
    result.manifests = sorted(p for p in texts if os.path.basename(p) in MANIFESTS)
    result.entry_points = sorted(p for p in texts if os.path.basename(p) in ENTRY_HINTS)
    result.languages = dict(Counter(LANG_BY_EXT[R.ext(p)] for p in texts if R.ext(p) in LANG_BY_EXT))

    result.file_index = [
        {"path": p, "language": LANG_BY_EXT.get(R.ext(p), "Config" if R.ext(p) in R.CONFIG_EXTS else "Other"),
         "size": len(t.encode("utf-8")), "lines": t.count("\n") + 1 if t else 0}
        for p, t in sorted(texts.items())]
    emit('security_and_quality', 60)
    seen = {}
    timed_out = False
    for rule in R.RULES:
        if timed_out:
            break
        if rule.check is not None:
            for path, text in texts.items():
                if time.monotonic() - started > time_budget:
                    timed_out = True
                    break
                if not rule.applies(path):
                    continue
                lines = text.splitlines()
                for hit in rule.check(path, lines):
                    key = (rule.id, path, hit.line)
                    if key not in seen:
                        seen[key] = _normalize(rule, path, hit, created_at, lines)
        if rule.check_repo is not None and not timed_out:
            if time.monotonic() - started > time_budget:
                timed_out = True
                break
            for path, hit in rule.check_repo({p: t for p, t in texts.items()}):
                key = (rule.id, path, hit.line)
                if key not in seen:
                    seen[key] = _normalize(rule, path, hit, created_at, texts.get(path, "").splitlines())
    if timed_out:
        result.partial, result.partial_reason = True, f"time budget of {time_budget:.0f}s reached"
    emit('correlation', 85)
    result.parse_failures = sorted(p for p, t in texts.items() if R.ext(p) == ".py" and not A.parses(t))
    if result.parse_failures:
        result.files_skipped["unparseable_python"] = len(result.parse_failures)
    kept, result.deduplicated = _deduplicate(list(seen.values()))
    result.findings = _correlate_and_score(kept)
    result.edges = G.extract_import_edges(texts)
    return result
